	/**
	 * Short-lived live containment loop (outside WordPress).
	 *
	 * @return string
	 */
	protected function script_guard() {
		return $this->bash_preamble() . <<<'BASH'
# Temporary live containment. Does not prove the site is clean when found=0.
INTERVAL="${INTERVAL:-5}"
load_site_env
WATCH="$DIR/watch-paths.txt"
MARKERS_RE='SC_ADV_BEGIN|SC_DB_BEGIN|SC_TH_BEGIN|SC_WC|__SC_BOOT|SCOCV|echo-updater-x|retadpu-ohce|wp_helper_uid|Widget cache bootstrap, ver b2ccbcd25e|Runtime dependencies bootstrap 9b66554fd3|wp_179e4b|wp_4bb239|wp_4960ab|8e753f173a5c428fe6c44646cddb0da04952628bcd098400d6fe9fcd3f3bb435|b6efe58fb91fb0bb9d11fce3b6eb42bcc1b8822deacc39facc657d17cffb1bf5'

if [[ ! -f "$WATCH" ]]; then
  echo "Missing watch-paths.txt" >&2
  exit 1
fi

log "guard: INTERVAL=${INTERVAL}s QUARANTINE_BASE=$QUARANTINE_BASE"
log "guard: Ctrl+C to stop. found=0 is NOT proof of clean."

pass=0
while true; do
  pass=$((pass + 1))
  found=0
  moved=0
  export QUARANTINE_RUN="$(date -u +%Y%m%d-%H%M%S)"

  while IFS= read -r path || [[ -n "$path" ]]; do
    [[ -z "$path" || "$path" == \#* ]] && continue
    [[ -e "$path" || -L "$path" ]] || continue

    base="$(basename "$path")"
    hit=0
    note=""

    # Exact known high-value basenames always count when present on the watch list.
    case "$base" in
      object-cache.php|advanced-cache.php|db.php|.user.ini|user.ini)
        if grep -Eq "$MARKERS_RE|auto_prepend_file" -- "$path" 2>/dev/null; then
          hit=1
          note="dropin/prepend marker"
        elif [[ "$base" == ".user.ini" || "$base" == "user.ini" ]]; then
          if grep -Eq 'auto_prepend_file' -- "$path" 2>/dev/null; then
            hit=1
            note="auto_prepend_file"
          fi
        fi
        ;;
      admin-helper.php|boot-loader.php)
        file_sha="$(sha256sum -- "$path" 2>/dev/null | awk '{print $1}')"
        if [[ "$file_sha" == "4bbeaed0845bcd965c92902a1dfb314d4afd79e48029dc22bf5fa7597a0d93cb" \
           || "$file_sha" == "0cbe6a757abcfe7c8968ae169929164d978f120847c05ca91f5e09c44293c4f3" ]]; then
          hit=1
          note="wp_helper_uid exact file hash"
        elif grep -Eq 'wp_helper_uid|Widget cache bootstrap, ver b2ccbcd25e|Runtime dependencies bootstrap 9b66554fd3|8e753f173a5c428fe6c44646cddb0da04952628bcd098400d6fe9fcd3f3bb435|b6efe58fb91fb0bb9d11fce3b6eb42bcc1b8822deacc39facc657d17cffb1bf5' -- "$path" 2>/dev/null; then
          hit=1
          note="wp_helper_uid sample"
        elif grep -Eq 'wp_179e4b' -- "$path" 2>/dev/null \
          && grep -Eq 'wp_4bb239' -- "$path" 2>/dev/null \
          && grep -Eq 'wp_4960ab' -- "$path" 2>/dev/null; then
          hit=1
          note="wp_helper_uid cluster probes"
        fi
        ;;
      wp-config.php)
        if grep -Eq 'SC_WC|SC_WC_BEGIN|__SC_BOOT|SCOCV' -- "$path" 2>/dev/null; then
          hit=1
          note="wp-config marker"
        fi
        ;;
      *)
        # Returning purge targets, or hex-named staging drops.
        if [[ "$base" =~ ^[0-9a-f]{8}\.(php|zip)$ ]]; then
          hit=1
          note="hex staging name"
        elif grep -Eq "$MARKERS_RE" -- "$path" 2>/dev/null; then
          hit=1
          note="content marker"
        else
          # Path was on the export purge list — any reappearance is an IOC.
          hit=1
          note="watchlist reappear"
        fi
        ;;
    esac

    if [[ "$hit" -eq 1 ]]; then
      found=$((found + 1))
      log "[IOC] $path ($note)"
      rel="$(rel_key_from_abspath "$path")"
      if [[ "$DRY_RUN" == "1" ]]; then
        log "[dry-run] would quarantine $path"
      else
        if quarantine_move "$path" "$rel"; then
          moved=$((moved + 1))
        else
          log "[FAIL] quarantine $path"
        fi
      fi
    fi
  done < "$WATCH"

  # Also spot hex staging artifacts under wp-content (cheap find, depth-limited).
  if [[ -n "${WP_CONTENT_DIR:-}" && -d "$WP_CONTENT_DIR" ]]; then
    while IFS= read -r -d '' path; do
      found=$((found + 1))
      log "[IOC] $path (hex scan)"
      rel="$(rel_key_from_abspath "$path")"
      if [[ "$DRY_RUN" == "1" ]]; then
        log "[dry-run] would quarantine $path"
      else
        if quarantine_move "$path" "$rel"; then
          moved=$((moved + 1))
        fi
      fi
    done < <(find "$WP_CONTENT_DIR" -xdev \( -name '[0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f].php' -o -name '[0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f].zip' \) -type f -print0 2>/dev/null | head -z -n 50)
  fi

  log "[SUMMARY] pass=$pass found=$found moved=$moved"
  sleep "$INTERVAL"
done

BASH;
	}
